"""PDF report generation using ReportLab."""
from __future__ import annotations

import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.models.scan import Scan


def _fmt_dt(dt: datetime | None) -> str:
    return dt.strftime("%Y-%m-%d %H:%M UTC") if dt else "—"


def generate_scan_report(scan: Scan) -> bytes:
    """Render a scan record into a PDF and return the bytes."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=2 * cm,
        rightMargin=2 * cm,
        topMargin=2 * cm,
        bottomMargin=2 * cm,
        title=f"DeepFake Report {scan.id}",
        author="DeepFake Detector",
    )
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle(
        "H1", parent=styles["Heading1"], textColor=colors.HexColor("#4f46e5")
    )
    h2 = ParagraphStyle(
        "H2", parent=styles["Heading2"], textColor=colors.HexColor("#111827")
    )
    body = styles["BodyText"]

    flow = []
    flow.append(Paragraph("DeepFake Detector — Detection Report", h1))
    flow.append(Spacer(1, 0.4 * cm))
    flow.append(Paragraph(f"Report ID: <b>{scan.id}</b>", body))
    flow.append(Paragraph(f"Generated: {_fmt_dt(datetime.utcnow())}", body))
    flow.append(Spacer(1, 0.6 * cm))

    flow.append(Paragraph("Scan summary", h2))
    summary_rows = [
        ["Type", scan.scan_type.value],
        ["Status", scan.status.value],
        ["Filename", scan.original_filename or "—"],
        ["Source URL", scan.source_url or "—"],
        ["MIME", scan.mime_type or "—"],
        ["Size (bytes)", str(scan.file_size or "—")],
        ["SHA-256", scan.file_hash or "—"],
        ["Created at", _fmt_dt(scan.created_at)],
        ["Completed at", _fmt_dt(scan.completed_at)],
    ]
    table = Table(summary_rows, colWidths=[5 * cm, 11 * cm])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f3f4f6")),
                ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#111827")),
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#e5e7eb")),
                ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
            ]
        )
    )
    flow.append(table)
    flow.append(Spacer(1, 0.6 * cm))

    flow.append(Paragraph("Result", h2))
    if scan.score is None:
        flow.append(Paragraph("Result not available.", body))
    else:
        score_pct = scan.score * 100
        result_rows = [
            ["Score", f"{scan.score:.4f} ({score_pct:.2f}%)"],
            ["Label", scan.label or "—"],
            ["Confidence", scan.confidence or "—"],
        ]
        rt = Table(result_rows, colWidths=[5 * cm, 11 * cm])
        rt.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eef2ff")),
                    ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                    ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#c7d2fe")),
                    ("FONTSIZE", (0, 0), (-1, -1), 10),
                ]
            )
        )
        flow.append(rt)
        flow.append(Spacer(1, 0.4 * cm))
        flow.append(Paragraph("Explanation", h2))
        flow.append(Paragraph(scan.explanation or "—", body))

    if scan.error_message:
        flow.append(Spacer(1, 0.4 * cm))
        flow.append(Paragraph("Error", h2))
        flow.append(Paragraph(scan.error_message, body))

    flow.append(Spacer(1, 1 * cm))
    flow.append(
        Paragraph(
            "<i>This report was generated by DeepFake Detector. "
            "Results are probabilistic and intended for guidance only.</i>",
            body,
        )
    )

    doc.build(flow)
    return buf.getvalue()
